import { chromium } from 'playwright'
const b = await chromium.launch()
const check = async (lang, expectText, expectLangAttr) => {
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
  await ctx.addInitScript((l) => localStorage.setItem('app-locale', l), lang)
  const p = await ctx.newPage()
  await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
  const html = await p.evaluate(() => document.documentElement.lang)
  const body = await p.textContent('body')
  const title = await p.title()
  console.log(`[${lang}] htmlLang=${html} title="${title.slice(0,40)}..." hasExpected=${body.includes(expectText)}`)
  // switcher presence
  const sw = await p.locator('.lang-switcher, [class*=lang]').count()
  console.log(`[${lang}] switcherElements=${sw}`)
  await ctx.close()
}
await check('en', 'SQL', 'en')
await check('ja', 'SQL', 'ja')
await check('ms', 'SQL', 'ms')
// dynamic switch test: load en, click switcher, choose 简体中文
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript(() => localStorage.setItem('app-locale', 'en'))
const p = await ctx.newPage()
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
const before = await p.textContent('h1').catch(() => '')
const trigger = p.locator('.lang-switcher').first()
await trigger.click()
await p.waitForTimeout(500)
const opt = p.locator('.arco-dropdown-option, li').filter({ hasText: '简体中文' }).first()
await opt.click()
await p.waitForTimeout(500)
const after = await p.textContent('h1').catch(() => '')
const langAttr = await p.evaluate(() => document.documentElement.lang)
console.log(`switch test: before="${before?.slice(0,30)}" after="${after?.slice(0,30)}" htmlLang=${langAttr}`)
await b.close()
